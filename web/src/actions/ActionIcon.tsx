export type ActionIconName = keyof typeof icons
export function ActionIcon({ name, className = '' }: { name: ActionIconName; className?: string }) {
  const Icon = icons[name] as ComponentType<{ size: number; className?: string }>
  return (
    <span className={`action-icon ${className}`.trim()} aria-hidden="true">
      <Icon size={16} />
    </span>
  )
}
